"""Step 4.5: measure NFR7 (core relations on 10,000 apps: at most 60 s and 2 GB peak memory).

Each scenario runs in a fresh process so that peak memory is its own. Inputs are 10,000 apps
sampled from the VS-AG validation partition; the models are LightGBM detectors trained on the
DR-AG (7,424 apps) or VS-AG (97,545 apps) training partition. Validation and training data only:
no test partition is read. Writes reports/nfr/benchmark.md and benchmark.csv.

Usage: python scripts/nfr_benchmark.py [--repeats 3]
"""

from __future__ import annotations

import argparse
import json
import platform
import resource
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "nfr"
N_APPS = 10_000
TIME_LIMIT_S = 60.0
MEMORY_LIMIT_MB = 2048.0
SCENARIOS = ("rq12-DR-AG", "rq12-VS-AG")


def peak_mb() -> float:
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return peak / (1024 * 1024) if sys.platform == "darwin" else peak / 1024


def child(train_split: str) -> None:
    """One measurement: train the model, then time the gate on 10,000 apps."""
    from shortcutcheck import gate
    from shortcutcheck.config import load_config
    from shortcutcheck.data.splits import load_part
    from shortcutcheck.training.baselines import build_model

    cfg = load_config()
    train = load_part(cfg, train_split, "train")
    apps = load_part(cfg, "rq12-VS-AG", "val").sample(n=N_APPS, random_state=11)
    x_train, y_train = gate.features(train, cfg), gate.labels(train)
    model = build_model("lgbm", 11).fit(x_train, y_train)
    x_apps = gate.features(apps, cfg)
    before = peak_mb()
    start = time.perf_counter()
    report = gate.check(model, x_train, y_train, x_apps, cfg, mrs=gate.CORE, sample=N_APPS)
    seconds = time.perf_counter() - start
    print(
        json.dumps(
            {
                "train_split": train_split,
                "n_train": len(train),
                "n_apps": report.n_checked,
                "seconds": round(seconds, 2),
                "peak_mb_process": round(peak_mb(), 1),
                "peak_mb_before_check": round(before, 1),
                "passed_gate": report.passed,
            }
        )
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--child", default=None, help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.child:
        child(args.child)
        return
    rows = []
    for split in SCENARIOS:
        for _ in range(args.repeats):
            out = subprocess.run(
                [sys.executable, __file__, "--child", split],
                capture_output=True,
                text=True,
                check=True,
                cwd=ROOT,
            )
            rows.append(json.loads(out.stdout.strip().splitlines()[-1]))
            print(rows[-1], flush=True)
    import pandas as pd

    frame = pd.DataFrame(rows)
    OUT.mkdir(parents=True, exist_ok=True)
    frame.to_csv(OUT / "benchmark.csv", index=False)
    summary = frame.groupby(["train_split", "n_train"], sort=False).agg(
        seconds_median=("seconds", "median"),
        seconds_max=("seconds", "max"),
        peak_mb_max=("peak_mb_process", "max"),
    )
    lines = [
        "# NFR7 benchmark (roadmap 4.5)",
        "",
        f"Generated by `python scripts/nfr_benchmark.py --repeats {args.repeats}`. Machine: "
        f"{platform.platform()}, {platform.processor() or platform.machine()}, Python "
        f"{platform.python_version()}. Target (NFR7): core relations (MR1, MR3, MR4 with the "
        f"realism check) for one fitted model on {N_APPS:,} apps in at most {TIME_LIMIT_S:.0f} s "
        f"and {MEMORY_LIMIT_MB:.0f} MB peak memory. Time covers fitting the relations and the "
        "realism check and running the gate (not training the model or loading data). Peak "
        "memory is the whole process, including data loading and model training.",
        "",
        "| Training data | Training apps | Median time (s) | Max time (s) | Time target met "
        "| Peak memory (MB) | Memory target met |",
        "| --- | ---: | ---: | ---: | --- | ---: | --- |",
    ]
    for (split, n_train), r in summary.iterrows():
        lines.append(
            f"| {split} | {n_train:,} | {r.seconds_median:.1f} | {r.seconds_max:.1f} | "
            f"{'yes' if r.seconds_max <= TIME_LIMIT_S else 'no'} | {r.peak_mb_max:.0f} | "
            f"{'yes' if r.peak_mb_max <= MEMORY_LIMIT_MB else 'no'} |"
        )
    lines += [
        "",
        "NFR7 names the MacBook Air as the target machine; rerun this script there for that "
        "measurement.",
        "",
    ]
    (OUT / "benchmark.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
