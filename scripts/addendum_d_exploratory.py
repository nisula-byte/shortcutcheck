"""EXPLORATORY (not pre-registered): is the H5b correlation more than a between-algorithm effect?

Reads reports/addendum_d/h5b_pool.csv and h4_rows.csv (from `shortcutcheck addendum d`) and
writes reports/addendum_d/exploratory.md. Opens no data. Nothing here changes a verdict in
h4.md or h5.md.

1. Spearman rho(mr4_monitor, decay) within each algorithm (un-injected models and full pool).
2. rho after removing algorithm means (ranks centred within algorithm).
3. |rho| of every monitoring signal, since confidence drop correlates in the direction opposite
   to the pre-registered orientation.
4. Permission-MR changes under the fix (H4 rows), as a cost check.

Usage: python scripts/addendum_d_exploratory.py
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import pandas as pd

from shortcutcheck.analysis.stats import spearman

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "reports" / "addendum_d"
SIGNALS = ["mr4_monitor", "psi", "confidence_drop", "atc_drop", "mr4_pre"]


def fmt(v: float) -> str:
    return "n/a" if pd.isna(v) else f"{v:.3f}"


def within(pool: pd.DataFrame) -> list[str]:
    out = [
        "| Subset | Algorithm | Models | ρ(mr4_monitor, decay) | ρ(psi, decay) |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    for subset, part in (("un-injected", pool[pool["skew"] == 0]), ("full pool", pool)):
        for alg, g in part.groupby("algorithm"):
            out.append(
                f"| {subset} | {alg} | {len(g)} | {fmt(spearman(g['mr4_monitor'], g['decay']))} "
                f"| {fmt(spearman(g['psi'], g['decay']))} |"
            )
    return out


def centred(pool: pd.DataFrame) -> list[str]:
    out = ["| Subset | Signal | ρ after removing algorithm means |", "| --- | --- | ---: |"]
    for subset, part in (("un-injected", pool[pool["skew"] == 0]), ("full pool", pool)):
        ranks = part[[*SIGNALS, "decay"]].rank()
        ranks["algorithm"] = part["algorithm"].to_numpy()
        c = ranks.groupby("algorithm").transform(lambda s: s - s.mean())
        for s in SIGNALS:
            out.append(f"| {subset} | {s} | {fmt(spearman(c[s], c['decay']))} |")
    return out


def magnitudes(pool: pd.DataFrame) -> list[str]:
    part = pool[pool["skew"] == 0]
    out = ["| Signal | ρ | abs(ρ) |", "| --- | ---: | ---: |"]
    for s in SIGNALS:
        r = spearman(part[s], part["decay"])
        out.append(f"| {s} | {fmt(r)} | {fmt(abs(r))} |")
    return out


def permission_cost(rows: pd.DataFrame) -> list[str]:
    out = ["| Split | MR | Baseline | Augmented | Change |", "| --- | --- | ---: | ---: | ---: |"]
    for split, g in rows.groupby("split", sort=False):
        for mr in ("rate_MR5", "rate_MR6"):
            b = g.loc[g["arm"] == "baseline", mr].mean()
            a = g.loc[g["arm"] == "augmented", mr].mean()
            out.append(f"| {split} | {mr[5:]} | {fmt(b)} | {fmt(a)} | {fmt(a - b)} |")
    return out


def main() -> None:
    pool = pd.read_csv(FOLDER / "h5b_pool.csv")
    rows = pd.read_csv(FOLDER / "h4_rows.csv")
    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True
    ).stdout.strip()
    lines = [
        "# Addendum D, exploratory checks",
        "",
        f"Generated by `python scripts/addendum_d_exploratory.py` at commit `{commit}` from "
        "`reports/addendum_d/h5b_pool.csv` and `h4_rows.csv`. **Exploratory, not "
        "pre-registered.** It does not change any verdict. Opens no data.",
        "",
        "## 1. H5b within each algorithm (30 un-injected or 60 pool models per algorithm)",
        "",
        *within(pool),
        "",
        "## 2. H5b after removing between-algorithm differences",
        "",
        *centred(pool),
        "",
        "## 3. Size of each signal's correlation (un-injected), whatever its sign",
        "",
        *magnitudes(pool),
        "",
        "## 4. Permission MRs under the fix (H4, means over 25 models)",
        "",
        *permission_cost(rows),
        "",
    ]
    (FOLDER / "exploratory.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
