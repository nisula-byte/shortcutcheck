"""EXPLORATORY (not pre-registered): is the Addendum B reversal specific to metadata?

Reads reports/rq2-dada/rows.csv and detection.csv (from `shortcutcheck addendum b`) and
writes reports/rq2-dada/exploratory.md. Opens no data. Nothing here changes the Addendum B
verdict, which is judged only in reports/rq2-dada/addendum_b.md.

Question: debiased-trained models flip more under the metadata MRs (MR1, MR3, MR4). Do they
also flip more under the permission MRs (MR5, MR6, D12), which do not touch metadata? If so,
the reversal shows a general loss of stability, not specifically more reliance on metadata.

Usage: python scripts/rq2_dada_exploratory.py
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import pandas as pd

from shortcutcheck.analysis.stats import cliffs_delta, wilcoxon_greater

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "reports" / "rq2-dada"
RUNS = ["VS-AG", "VS-AG-size-matched", "VS-AG_deb"]
MRS = ["MR1", "MR3", "MR4", "MR5", "MR6"]
PAIR = ["algorithm", "seed"]


def fmt(v: float) -> str:
    return "n/a" if pd.isna(v) else (f"{v:.1e}" if v < 1e-3 else f"{v:.3f}")


def rate_table(rows: pd.DataFrame, role: str) -> list[str]:
    r = rows[(rows["role"] == role) & (rows["stratum"] == "all") & rows["run"].isin(RUNS)]
    t = r.pivot_table(index="run", columns="mr", values="rate", aggfunc="mean")
    t = t.reindex(index=RUNS, columns=[m for m in MRS if m in t.columns])
    out = ["| Run | " + " | ".join(t.columns) + " |", "| --- |" + " ---: |" * len(t.columns)]
    for run, r_ in t.iterrows():
        out.append(f"| {run} | " + " | ".join(fmt(v) for v in r_) + " |")
    ratio = t.loc["VS-AG_deb"] / t.loc["VS-AG"]
    out.append("| ratio debiased / published | " + " | ".join(f"{v:.1f}x" for v in ratio) + " |")
    return out


def paired_tests(rows: pd.DataFrame, role: str) -> list[str]:
    r = rows[(rows["role"] == role) & (rows["stratum"] == "all")]
    out = [
        "| Comparison | MR | Pairs | p (two-sided) | Cliff's δ (published − debiased) |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    for base in ["VS-AG", "VS-AG-size-matched"]:
        for mr in [m for m in MRS if m in set(r["mr"])]:
            a = r[(r["run"] == base) & (r["mr"] == mr)].set_index(PAIR)["rate"]
            b = r[(r["run"] == "VS-AG_deb") & (r["mr"] == mr)].set_index(PAIR)["rate"]
            j = pd.concat([a, b], axis=1, keys=["a", "b"]).dropna()
            res = wilcoxon_greater((j["a"] - j["b"]).to_numpy())
            d = cliffs_delta(j["a"].to_numpy(), j["b"].to_numpy())
            out.append(
                f"| {base} vs VS-AG_deb | {mr} | {len(j)} | {fmt(res.p_two_sided)} | {d:.2f} |"
            )
    return out


def f1_table(det: pd.DataFrame) -> list[str]:
    d = det[det["run"].isin(RUNS)]
    t = d.pivot_table(index="run", columns="eval_split", values="f1", aggfunc="mean").reindex(RUNS)
    out = ["| Run | " + " | ".join(t.columns) + " |", "| --- |" + " ---: |" * len(t.columns)]
    for run, r_ in t.iterrows():
        out.append(f"| {run} | " + " | ".join(fmt(v) for v in r_) + " |")
    return out


def main() -> None:
    rows = pd.read_csv(FOLDER / "rows.csv")
    det = pd.read_csv(FOLDER / "detection.csv")
    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True
    ).stdout.strip()
    lines = [
        "# Addendum B, exploratory: is the reversal specific to metadata?",
        "",
        f"Generated by `python scripts/rq2_dada_exploratory.py` at commit `{commit}` from "
        "`reports/rq2-dada/rows.csv` and `detection.csv`. **Exploratory, not pre-registered.** "
        "It does not change the Addendum B verdict (`addendum_b.md`). Opens no data.",
        "",
        "MR1, MR3 and MR4 perturb metadata only; MR5 and MR6 perturb permissions (D12) and do "
        "not touch metadata. Rates are means over 25 models (5 algorithms x 5 seeds), "
        "stratum `all`. MR5 does not apply to the `h2-biased` inputs.",
        "",
        "## Violation rates on Dada's debiased VS test file (`h2-deb`)",
        "",
        *rate_table(rows, "h2-deb"),
        "",
        "## Violation rates on Dada's biased VS test file (`h2-biased`)",
        "",
        *rate_table(rows, "h2-biased"),
        "",
        "## Paired comparisons on `h2-deb` (pairs matched by algorithm and seed)",
        "",
        "Two-sided Wilcoxon, no multiplicity correction (exploratory).",
        "",
        *paired_tests(rows, "h2-deb"),
        "",
        "## Detection F1 on the same test files",
        "",
        *f1_table(det),
        "",
    ]
    (FOLDER / "exploratory.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
