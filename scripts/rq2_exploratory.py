"""EXPLORATORY (not pre-registered): where the RQ2 reversal comes from.

Reads reports/rq2/rows.csv and detection.csv (from `make rq2`) and writes
reports/rq2/exploratory.md: MR1/MR4 violation rates on the h2-deb inputs by year validity
(D11) and by algorithm, and detection F1 on the same inputs. Opens no data. Nothing here
decides a hypothesis; H2 is judged only in reports/rq2/h2.md.

Usage: python scripts/rq2_exploratory.py
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "reports" / "rq2"
RUNS = ["DR-AG", "DR-AG_deb", "VS-AG", "VS-AG_deb"]


def table(frame: pd.DataFrame, index: list[str], columns: str, value: str) -> list[str]:
    t = frame.pivot_table(index=index, columns=columns, values=value, aggfunc="mean")
    head = "| " + " | ".join([*index, *map(str, t.columns)]) + " |"
    sep = "| " + " | ".join(["---"] * len(index) + ["---:"] * len(t.columns)) + " |"
    rows = []
    for key, r in t.iterrows():
        keys = key if isinstance(key, tuple) else (key,)
        rows.append("| " + " | ".join([*map(str, keys), *(f"{v:.3f}" for v in r)]) + " |")
    return [head, sep, *rows]


def main() -> None:
    rows = pd.read_csv(FOLDER / "rows.csv")
    det = pd.read_csv(FOLDER / "detection.csv")
    r = rows[(rows["role"] == "h2-deb") & rows["mr"].isin(["MR1", "MR4"]) & rows["run"].isin(RUNS)]
    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True
    ).stdout.strip()
    lines = [
        "# RQ2 exploratory breakdown (NOT pre-registered)",
        "",
        f"Generated by `python scripts/rq2_exploratory.py` at commit `{commit}` from "
        "`reports/rq2/rows.csv` and `detection.csv`. Descriptive only: H2 is judged in "
        "`h2.md`. Inputs: each family's debiased test partition with trained-on apps removed "
        "(h2-deb). Means over 5 seeds (and over algorithms where not split by algorithm).",
        "",
        "## MR1 and MR4 violation rate by year validity (D11)",
        "",
        *table(r, ["run", "mr"], "stratum", "rate"),
        "",
        "## MR1 and MR4 violation rate by algorithm (all inputs)",
        "",
        *table(r[r["stratum"] == "all"], ["run", "mr"], "algorithm", "rate"),
        "",
        "## Detection F1 on the same inputs",
        "",
        *table(det[det["role"] == "h2-deb"], ["run"], "algorithm", "f1"),
        "",
    ]
    (FOLDER / "exploratory.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
