"""Runtime of ShortcutCheck on the reference platform, for the paper's cost section.

Times, on validation partitions only (no test access): fitting the MRs and the realism check,
evaluating every MR on up to 5,000 inputs for one trained model, and building the augmented
training set. Writes reports/paper/runtime.md and runtime.csv.

Usage: python scripts/paper_runtime.py
"""

from __future__ import annotations

import os
import platform
import time
from pathlib import Path

import numpy as np
import pandas as pd

from shortcutcheck.addenda.fix_poc import augment
from shortcutcheck.config import load_config
from shortcutcheck.data.splits import load_part
from shortcutcheck.evaluation.experiment import fit_mrs
from shortcutcheck.mrs.realism import RealismCheck
from shortcutcheck.runner.engine import run_mr, single_threaded
from shortcutcheck.training.baselines import build_model
from shortcutcheck.training.features import select

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "paper"
SPLITS = ("rq12-DR-AG", "rq12-VS-AG")
ALGORITHMS = ("lr", "rf", "lgbm")
MRS = ("MR1", "MR3", "MR4", "MR5", "MR6")


def main() -> None:
    cfg = load_config()
    args = (cfg.metadata_columns, cfg.id_column, cfg.dropped_features)
    rows = []
    for split in SPLITS:
        x_tr, y_tr = select(load_part(cfg, split, "train"), "full", *args)
        x_va, _ = select(load_part(cfg, split, "val"), "full", *args)
        x_va = x_va.reindex(columns=x_tr.columns)
        if len(x_va) > 5000:
            idx = np.sort(np.random.default_rng(11).choice(len(x_va), 5000, replace=False))
            x_va = x_va.iloc[idx].reset_index(drop=True)
        meta = [c for c in cfg.metadata_columns if c in x_tr.columns]
        t = time.perf_counter()
        realism = RealismCheck(seed=11, metadata_columns=meta).fit(x_tr)
        mrs = {m.mr_id: m for m in fit_mrs(cfg, x_tr, y_tr, MRS)}
        fit_s = time.perf_counter() - t
        t = time.perf_counter()
        x_aug, _, _ = augment(x_tr, y_tr, mrs["MR4"], realism, 11)
        aug_s = time.perf_counter() - t
        for alg in ALGORITHMS:
            model = build_model(alg, 11).fit(x_tr, y_tr)
            t = time.perf_counter()
            with single_threaded(model):
                for mr in MRS:
                    if mr in mrs:
                        run_mr(model, mrs[mr], x_va, seed=11, realism=realism)
            eval_s = time.perf_counter() - t
            rows.append(
                {
                    "split": split,
                    "train_apps": len(x_tr),
                    "inputs": len(x_va),
                    "algorithm": alg,
                    "fit_mrs_and_realism_s": round(fit_s, 1),
                    "all_mrs_one_model_s": round(eval_s, 1),
                    "augment_training_set_s": round(aug_s, 1),
                    "augmented_rows": len(x_aug),
                }
            )
    OUT.mkdir(parents=True, exist_ok=True)
    frame = pd.DataFrame(rows)
    frame.to_csv(OUT / "runtime.csv", index=False)
    head = (
        f"# ShortcutCheck runtime\n\nGenerated by `python scripts/paper_runtime.py` on "
        f"{platform.platform()}, {os.cpu_count()} CPU cores, Python {platform.python_version()}. "
        "Validation partitions only (no test access); MR inputs capped at 5,000.\n\n"
    )
    cols = list(frame.columns)
    table = ["| " + " | ".join(cols) + " |", "|" + " --- |" * len(cols)]
    table += ["| " + " | ".join(str(v) for v in r) + " |" for r in frame.itertuples(index=False)]
    (OUT / "runtime.md").write_text(head + "\n".join(table) + "\n", encoding="utf-8")
    print(head + "\n".join(table))


if __name__ == "__main__":
    main()
