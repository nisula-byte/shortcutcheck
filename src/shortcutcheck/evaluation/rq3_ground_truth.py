"""Roadmap step 3.7: ground truth for RQ3, the real F1 drop of every pool model.

F1 drop = F1 on the 2012-14 validation partition - F1 on the 2017-19 test partition, both at
threshold 0.5 (PREREGISTRATION.md section 5). Also per test year (2017, 2018, 2019; D9).

Test labels are used ONLY here, and each pool model gets exactly ONE ``load_test()`` call,
logged with the model's id (the roadmap's Check). Nothing here computes or reads a signal; the
signals were fixed in step 3.6 before any label was used. ``assemble_pool`` joins the two
tables into the ``analysis/h3.POOL_COLUMNS`` table that step 3.8 judges.

``dry_run=True`` reads the VALIDATION partition in place of the test partition, so the whole
step can be exercised on real data without opening any test label.
"""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import f1_score

from shortcutcheck.analysis.h3 import POOL_COLUMNS
from shortcutcheck.config import Config
from shortcutcheck.data.splits import load_part
from shortcutcheck.evaluation.locked_test import access_log, load_test
from shortcutcheck.experiments.spec import Experiment
from shortcutcheck.runner.engine import single_threaded
from shortcutcheck.training.features import select
from shortcutcheck.training.pool import pool_members


def n_test_accesses(cfg: Config) -> int:
    return len(access_log(cfg))


def f1_at(model: object, x: pd.DataFrame, y: pd.Series, threshold: float) -> float:
    cols = list(model.feature_names_in_)  # type: ignore[attr-defined]
    with single_threaded(model):
        p = model.predict_proba(x[cols])[:, 1]  # type: ignore[attr-defined]
    return float(f1_score(y, (p >= threshold).astype(int), zero_division=0))


def ground_truth(
    cfg: Config,
    exp: Experiment,
    model_dir: Path,
    *,
    dry_run: bool = False,
    progress: Callable[[str], None] | None = None,
) -> pd.DataFrame:
    split = str(exp.pool["split"])
    truth = exp.pool["ground_truth"]
    threshold = float(truth["threshold"])
    years = [int(y) for y in truth["by_test_year"]]
    args = (cfg.metadata_columns, cfg.id_column, cfg.dropped_features)
    x_val, y_val = select(load_part(cfg, split, "val"), "full", *args)
    members = pool_members(exp)
    missing = [m.model for m in members if not (model_dir / f"{m.model}.joblib").exists()]
    if missing:
        raise FileNotFoundError(f"{len(missing)} pool models missing (run step 3.5): {missing[:3]}")
    rows = []
    for m in members:
        model = joblib.load(model_dir / f"{m.model}.joblib")
        if dry_run:
            frame = load_part(cfg, split, "val")
        else:
            frame = load_test(
                cfg,
                split,
                purpose=f"rq3 ground truth (roadmap step 3.7), model {m.model}: F1 on 2017-19 "
                "labels, one call per model",
            )
        x_test, y_test = select(frame, "full", *args)
        f1_val = f1_at(model, x_val, y_val, threshold)
        f1_test = f1_at(model, x_test, y_test, threshold)
        row: dict[str, object] = {
            "model": m.model,
            "f1_val": f1_val,
            "f1_test": f1_test,
            "f1_drop": f1_val - f1_test,
            "n_test": len(y_test),
        }
        year = x_test["year"].to_numpy(dtype=float)
        for y in years:
            mask = year == y
            row[f"n_test_{y}"] = int(mask.sum())
            row[f"f1_drop_{y}"] = (
                f1_val - f1_at(model, x_test[mask], y_test[mask], threshold)
                if mask.any()
                else float("nan")
            )
        rows.append(row)
        if progress:
            progress(m.model)
    return pd.DataFrame(rows)


def assemble_pool(signals: pd.DataFrame, truth: pd.DataFrame, commit: str) -> pd.DataFrame:
    """The table step 3.8 judges: one row per model, every pre-registered column."""
    keep = [c for c in signals.columns if c != "git_commit"]
    pool = signals[keep].merge(truth, on="model", how="left", validate="one_to_one")
    pool["signals_commit"] = signals["git_commit"].iloc[0] if "git_commit" in signals else ""
    pool["git_commit"] = commit
    absent = [c for c in POOL_COLUMNS if c not in pool.columns]
    if absent:
        raise ValueError(f"Pool table lacks pre-registered columns: {absent}")
    if pool["f1_drop"].isna().any():
        raise ValueError("A pool model has no ground truth.")
    return pool


def render_truth(truth: pd.DataFrame, pool: pd.DataFrame, n_log: int, commit: str) -> str:
    by = (
        pool.groupby(["algorithm", "skew"], sort=False)[["f1_val", "f1_test", "f1_drop"]]
        .mean()
        .reset_index()
    )
    lines = [
        "# RQ3 ground truth (roadmap step 3.7)",
        "",
        f"Generated by `shortcutcheck experiment ground-truth configs/experiments/rq3.yaml` at "
        f"commit `{commit}`. F1 at threshold 0.5 on 2012-14 validation and on 2017-19 test "
        f"inputs. One `load_test()` call per model: {n_log} logged calls for {len(truth)} models "
        "(`logs/test_access.jsonl`). Hypotheses are judged in `h3.md`, not here.",
        "",
        f"Mean F1 drop over all models: {pool['f1_drop'].mean():.3f} "
        f"(range {pool['f1_drop'].min():.3f} to {pool['f1_drop'].max():.3f}).",
        "",
        "| Algorithm | Skew | Validation F1 | 2017-19 F1 | F1 drop |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for t in by.itertuples():
        lines.append(
            f"| {t.algorithm} | {t.skew:g} | {t.f1_val:.3f} | {t.f1_test:.3f} "
            f"| {t.f1_drop:.3f} |"
        )
    year_cols = [c for c in pool.columns if c.startswith("f1_drop_")]
    if year_cols:
        lines += [
            "",
            "Mean F1 drop by test year (D9): "
            + ", ".join(f"{c[-4:]} {np.nanmean(pool[c]):.3f}" for c in year_cols)
            + ".",
        ]
    return "\n".join(lines) + "\n"
