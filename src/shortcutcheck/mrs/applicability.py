"""Which core MRs can be applied to each frozen split (evidence for decision D10).

Fits MR1-MR4 on the **training** partition only and records whether each one applies, and
why not if it does not. Also profiles the metadata columns the MRs change.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from shortcutcheck.config import Config
from shortcutcheck.data.splits import load_part
from shortcutcheck.mrs.base import NotApplicableError
from shortcutcheck.mrs.core import core_mrs
from shortcutcheck.training.features import select


@dataclass(frozen=True)
class SplitApplicability:
    split: str
    n_train: int
    mrs: dict[str, str]  # MR id -> "applies" or the reason it does not
    zero_share: dict[str, float]  # metadata column -> share of 0 (Dada's "missing")
    invalid_year_share: float
    malware_share_invalid_year: float
    malware_share_valid_year: float
    valid_years: tuple[int, ...]


def default_splits(cfg: Config) -> list[str]:
    return [*cfg.rq12_splits, f"rq3-{cfg.rq3_primary}"]


def check_split(cfg: Config, split: str) -> SplitApplicability:
    train = load_part(cfg, split, "train")
    x, y = select(train, "full", cfg.metadata_columns, cfg.id_column, cfg.dropped_features)
    valid = (cfg.android_first_year, cfg.collection_year)
    outcome: dict[str, str] = {}
    for mr in core_mrs(list(x.columns), valid):
        try:
            mr.fit(x, y)
            outcome[mr.mr_id] = "applies"
        except NotApplicableError as err:
            outcome[mr.mr_id] = f"not applicable: {err}"
    meta = [c for c in cfg.metadata_columns if c in x.columns]
    year = x["year"].to_numpy(dtype=float)
    invalid = (year < valid[0]) | (year > valid[1])
    labels = y.to_numpy()
    return SplitApplicability(
        split=split,
        n_train=len(x),
        mrs=outcome,
        zero_share={c: float((x[c] == 0).mean()) for c in meta},
        invalid_year_share=float(invalid.mean()),
        malware_share_invalid_year=float(labels[invalid].mean()) if invalid.any() else np.nan,
        malware_share_valid_year=float(labels[~invalid].mean()) if (~invalid).any() else np.nan,
        valid_years=tuple(int(v) for v in np.unique(year[~invalid])),
    )


def _pct(value: float) -> str:
    return "–" if np.isnan(value) else f"{value:.1%}"


def render_markdown(rows: list[SplitApplicability], commit: str) -> str:
    ids = sorted({k for r in rows for k in r.mrs})
    meta = sorted({k for r in rows for k in r.zero_share})
    lines = [
        "# Core MR applicability (roadmap step 2.2, decision D10)",
        "",
        f"Generated by `shortcutcheck mrs applicability` from the **training** partition of each "
        f"frozen split, after the D3/D4 column drops. Git commit `{commit}`. Do not edit by hand.",
        "",
        "## Which MRs apply",
        "",
        "| Split | Training apps | " + " | ".join(ids) + " |",
        "| --- | ---: | " + " | ".join("---" for _ in ids) + " |",
    ]
    for r in rows:
        cells = ["yes" if r.mrs.get(i) == "applies" else "**no**" for i in ids]
        lines.append(f"| {r.split} | {r.n_train} | " + " | ".join(cells) + " |")
    reasons = {(r.split, i): m for r in rows for i, m in r.mrs.items() if m != "applies"}
    if reasons:
        lines += ["", "Reasons:", ""]
        lines += [
            f"- {s}, {i}: {m.removeprefix('not applicable: ').removeprefix(f'{i}: ')}"
            for (s, i), m in reasons.items()
        ]
    lines += [
        "",
        "## Metadata profile",
        "",
        "Zero means missing in Dada. Invalid year = before "
        "Android (2008) or after collection (2021), mostly 1980, the ZIP format's default date.",
        "",
        "| Split | "
        + " | ".join(f"{c} = 0" for c in meta)
        + " | Invalid year | Malware share, invalid year | Malware share, valid year "
        "| Valid years seen |",
        "| --- | " + " | ".join("---:" for _ in meta) + " | ---: | ---: | ---: | --- |",
    ]
    for r in rows:
        years = f"{r.valid_years[0]}–{r.valid_years[-1]}" if r.valid_years else "none"
        lines.append(
            f"| {r.split} | "
            + " | ".join(_pct(r.zero_share[c]) for c in meta)
            + f" | {_pct(r.invalid_year_share)} | {_pct(r.malware_share_invalid_year)} "
            f"| {_pct(r.malware_share_valid_year)} | {years} ({len(r.valid_years)}) |"
        )
    return "\n".join(lines) + "\n"
