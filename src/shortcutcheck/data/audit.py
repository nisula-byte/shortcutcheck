"""Step 1.4: data audit.

For every Dada set: rows, unique hashes, label coverage, class balance and year range. Then
the RQ3 rule: each candidate needs labelled apps of both classes in the early (2014) and late
(2017) sets, at least ``rq3_min_per_class_per_year`` per class. If no candidate passes, the
report says so and points to the VirusShare-per-year fallback.
"""

from __future__ import annotations

from dataclasses import dataclass

import pandas as pd

from shortcutcheck.data.dada import LABEL, DadaSet, match_sets, read_set

YEAR_COLUMNS = ("year", "Year")


@dataclass(frozen=True)
class SetSummary:
    name: str
    rows: int
    unique_hashes: int
    labelled: bool
    unlabelled_rows: int
    goodware: int
    malware: int
    year_min: float | None
    year_max: float | None

    @property
    def malware_ratio(self) -> float | None:
        total = self.goodware + self.malware
        return None if total == 0 else self.malware / total


@dataclass(frozen=True)
class RQ3Verdict:
    candidate: str
    early_sets: list[str]
    late_sets: list[str]
    early_counts: tuple[int, int]
    late_counts: tuple[int, int]
    minimum: int

    @property
    def passes(self) -> bool:
        return bool(self.early_sets and self.late_sets) and (
            min(*self.early_counts, *self.late_counts) >= self.minimum
        )


def summarise(frame: pd.DataFrame, name: str, id_column: str) -> SetSummary:
    year_col = next((c for c in YEAR_COLUMNS if c in frame.columns), None)
    years = pd.to_numeric(frame[year_col], errors="coerce") if year_col else pd.Series(dtype=float)
    labelled = LABEL in frame.columns
    labels = frame[LABEL] if labelled else pd.Series(dtype=float)
    return SetSummary(
        name=name,
        rows=len(frame),
        unique_hashes=int(frame[id_column].nunique()),
        labelled=labelled,
        unlabelled_rows=int(labels.isna().sum()) if labelled else len(frame),
        goodware=int((labels == 0).sum()) if labelled else 0,
        malware=int((labels == 1).sum()) if labelled else 0,
        year_min=float(years.min()) if years.notna().any() else None,
        year_max=float(years.max()) if years.notna().any() else None,
    )


def _class_counts(summaries: list[SetSummary]) -> tuple[int, int]:
    return sum(s.goodware for s in summaries), sum(s.malware for s in summaries)


def rq3_verdicts(
    sets: list[DadaSet],
    summaries: dict[str, SetSummary],
    candidates: dict[str, dict[str, str]],
    minimum: int,
) -> list[RQ3Verdict]:
    verdicts = []
    for name, globs in candidates.items():
        early = [s.name for s in match_sets(sets, globs["early"])]
        late = [s.name for s in match_sets(sets, globs["late"])]
        verdicts.append(
            RQ3Verdict(
                candidate=name,
                early_sets=early,
                late_sets=late,
                early_counts=_class_counts([summaries[n] for n in early]),
                late_counts=_class_counts([summaries[n] for n in late]),
                minimum=minimum,
            )
        )
    return verdicts


def run_audit(
    sets: list[DadaSet], id_column: str, candidates: dict[str, dict[str, str]], minimum: int
) -> tuple[list[SetSummary], list[RQ3Verdict]]:
    summaries = [summarise(read_set(s, id_column), s.name, id_column) for s in sets]
    by_name = {s.name: s for s in summaries}
    return summaries, rq3_verdicts(sets, by_name, candidates, minimum)


def _fmt(value: float | None, digits: int = 0) -> str:
    if value is None:
        return "–"
    return f"{value:.{digits}f}"


def render_markdown(summaries: list[SetSummary], verdicts: list[RQ3Verdict], source: str) -> str:
    lines = [
        "# Data audit (roadmap step 1.4)",
        "",
        f"Generated by `shortcutcheck data audit` from `{source}`. Do not edit by hand.",
        "",
        "| Set | Rows | Unique hashes | Labelled | Unlabelled rows | Goodware | Malware "
        "| Malware ratio | Year min | Year max |",
        "| --- | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for s in summaries:
        lines.append(
            f"| {s.name} | {s.rows} | {s.unique_hashes} | {'yes' if s.labelled else 'no'} "
            f"| {s.unlabelled_rows} | {s.goodware} | {s.malware} "
            f"| {_fmt(s.malware_ratio, 3)} | {_fmt(s.year_min)} | {_fmt(s.year_max)} |"
        )
    lines += ["", "## RQ3 sufficiency (Check for step 1.4)", ""]
    lines += [
        "| Candidate | Early sets | Late sets | Early good/mal | Late good/mal | Minimum "
        "| Result |",
        "| --- | --- | --- | --- | --- | ---: | --- |",
    ]
    for v in verdicts:
        lines.append(
            f"| {v.candidate} | {', '.join(v.early_sets) or 'none matched'} "
            f"| {', '.join(v.late_sets) or 'none matched'} "
            f"| {v.early_counts[0]}/{v.early_counts[1]} | {v.late_counts[0]}/{v.late_counts[1]} "
            f"| {v.minimum} | {'PASS' if v.passes else 'FAIL'} |"
        )
    passing = [v.candidate for v in verdicts if v.passes]
    lines.append("")
    if passing:
        lines.append(f"**Check: PASS.** RQ3 can use: {', '.join(passing)}.")
    else:
        lines.append(
            "**Check: FAIL.** No candidate has enough labelled apps of both classes in both "
            "years. Switch RQ3 to the VirusShare-per-year fallback (VS15-VS18 malware with "
            "AZ19 yearly goodware), record why in the methodology chapter, and redesign RQ3 "
            "now, before Gate 1."
        )
    lines += [
        "",
        "Manual checks still required: confirm what `year` means in the Dada README, and "
        "whether `Year`/`APK size` duplicate `year`/`apk_size`.",
        "",
    ]
    return "\n".join(lines)
