"""Pilot RQ1 (roadmap step 2.7), exactly as stated in ``docs/pilot_plan.md``.

5 algorithms x 2 feature sets x 5 seeds on one frozen split. Every applicable MR runs on the
whole validation partition with the realism filter on. One MLflow run per model. The Gate 2
criteria are evaluated in code as written in the plan.

Since step 3.1 the pilot runs through the shared ``models`` engine
(``shortcutcheck.evaluation.experiment``), the same code RQ1 and RQ2 use. ``make pilot-compare``
confirms that this reproduces the committed pilot numbers exactly.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import pandas as pd

from shortcutcheck.config import Config
from shortcutcheck.evaluation.experiment import KEY_COLUMNS, run_experiment
from shortcutcheck.experiments.spec import MR_IDS, Experiment, ModelRun, Target
from shortcutcheck.training.baselines import ALL_ALGORITHMS
from shortcutcheck.training.features import FeatureSet

FEATURE_SETS: tuple[FeatureSet, ...] = ("full", "behaviour")
CORE = ("MR1", "MR2", "MR3", "MR4")
CLEAR_LOWER = 0.01  # plan: "clearly non-zero" = 95% CI lower bound above 1% for every seed
MIN_ALGORITHMS = 3


@dataclass(frozen=True)
class PilotResult:
    split: str
    commit: str
    rows: pd.DataFrame  # one row per (algorithm, feature set, seed, MR, stratum)
    detection: pd.DataFrame  # one row per (algorithm, feature set, seed)


PILOT_CONFIG = Path("configs/experiments/pilot.yaml")


def pilot_experiment(cfg: Config, split: str) -> Experiment:
    """The pilot as an experiment: the step 2.7 plan, on any frozen split (default DR-AG)."""
    return Experiment(
        path=PILOT_CONFIG,
        experiment="pilot",
        step="2.7",
        engine="models",
        mlflow_experiment=f"phase2-pilot-{split}",
        seeds=tuple(cfg.seeds),
        algorithms=ALL_ALGORITHMS,
        feature_sets=FEATURE_SETS,
        mrs=MR_IDS,
        realism=True,
        mr_sample=None,
        sample_seed=cfg.split_seed,
        runs=(ModelRun(split, split, "published", (Target(split, "val", "own"),)),),
    )


def run_pilot(cfg: Config, split: str, commit: str) -> PilotResult:
    """Step 2.7 through the shared ``models`` engine; columns as in the committed pilot CSV."""
    result = run_experiment(cfg, pilot_experiment(cfg, split), commit)
    rows = result.rows.drop(columns=KEY_COLUMNS)
    detection = result.detection.drop(columns=[*KEY_COLUMNS, "n_inputs"])
    return PilotResult(split, commit, rows, detection)


# ---- Gate 2 ---------------------------------------------------------------------------


@dataclass(frozen=True)
class Gate2:
    behaviour_exact_zero: bool
    behaviour_offenders: list[str]
    clear_algorithms: dict[str, list[str]]  # algorithm -> core MRs clearly non-zero

    @property
    def biased_non_zero(self) -> bool:
        return sum(bool(v) for v in self.clear_algorithms.values()) >= MIN_ALGORITHMS

    @property
    def passes(self) -> bool:
        return self.behaviour_exact_zero and self.biased_non_zero


def gate2(result: PilotResult) -> Gate2:
    r = result.rows[result.rows["stratum"] == "all"]
    core = r[r["mr"].isin(CORE)]
    beh = core[core["feature_set"] == "behaviour"]
    bad = beh[(beh["n_violations"] > 0) | (beh["max_abs_delta"].fillna(0) > 0)]
    offenders = sorted({f"{a}/{m}/s{s}" for a, m, s in bad[["algorithm", "mr", "seed"]].values})
    full = core[core["feature_set"] == "full"]
    clear: dict[str, list[str]] = {}
    for algorithm, g in full.groupby("algorithm", sort=False):
        ok = g.groupby("mr")["rate_low"].min()
        clear[str(algorithm)] = sorted(str(m) for m, low in ok.items() if low > CLEAR_LOWER)
    return Gate2(not offenders, offenders, clear)


# ---- report -----------------------------------------------------------------------------


def _f(v: float, d: int = 3) -> str:
    return "–" if pd.isna(v) else f"{v:.{d}f}"


def render_markdown(result: PilotResult) -> str:
    g = gate2(result)
    det = (
        result.detection.groupby(["algorithm", "feature_set"], sort=False)[
            ["f1", "pr_auc", "roc_auc", "fpr_at_95tpr"]
        ]
        .agg(["mean", "std"])
        .reset_index()
    )
    lines = [
        f"# Pilot RQ1 on `{result.split}` (roadmap step 2.7)",
        "",
        f"Generated by `shortcutcheck pilot` (`make pilot`). Git commit `{result.commit}`. Plan "
        "and Gate 2 criteria: `docs/pilot_plan.md`, committed before this run. Validation "
        "partition only; test set untouched. Per-model MLflow run IDs are in the CSV next to "
        "this file.",
        "",
        "## Gate 2",
        "",
        "| Criterion | Result |",
        "| --- | --- |",
        "| 1. Known-answer tests pass | yes (step 2.5, `reports/known_answers.md`) |",
        "| 2. Behaviour-only models exactly 0 on MR1–MR4 | "
        + ("**yes**" if g.behaviour_exact_zero else "**no**: " + ", ".join(g.behaviour_offenders))
        + " |",
    ]
    clear = "; ".join(f"{a}: {', '.join(m) or 'none'}" for a, m in g.clear_algorithms.items())
    n_clear = sum(bool(v) for v in g.clear_algorithms.values())
    lines += [
        f"| 3. Full-feature models clearly non-zero (95% CI lower bound > {CLEAR_LOWER:g} for "
        f"all 5 seeds) on a core MR, for at least {MIN_ALGORITHMS} of 5 algorithms "
        f"| {'**yes**' if g.biased_non_zero else '**no**'}: {n_clear} of 5 ({clear}) |",
        "",
        f"**Gate 2 (pilot part): {'PASS' if g.passes else 'FAIL'}.**",
        "",
        "## Detection quality (validation, mean ± SD over 5 seeds)",
        "",
        "| Algorithm | Features | F1 | PR-AUC | ROC-AUC | FPR@95%TPR |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for _, row in det.iterrows():
        cells = [
            f"{row[(m, 'mean')]:.3f} ± {row[(m, 'std')]:.3f}"
            for m in ("f1", "pr_auc", "roc_auc", "fpr_at_95tpr")
        ]
        lines.append(
            f"| {row[('algorithm', '')]} | {row[('feature_set', '')]} | " + " | ".join(cells) + " |"
        )
    r = result.rows
    allr = r[r["stratum"] == "all"]
    lines += [
        "",
        "## Violation rates (realism filter on)",
        "",
        "Mean over 5 seeds; in brackets the smallest and largest per-seed 95% CI bound. "
        "*Unfiltered* = same models without the realism filter. Counted = mean inputs counted "
        "per seed.",
        "",
        "| Algorithm | Features | MR | Counted | Violation rate [lowest low, highest high] "
        "| Unfiltered | Mean abs. change in p |",
        "| --- | --- | --- | ---: | --- | ---: | ---: |",
    ]
    for (a, fs, mr), grp in allr.groupby(["algorithm", "feature_set", "mr"], sort=False):
        lines.append(
            f"| {a} | {fs} | {mr} | {grp['n_counted'].mean():.0f} | {_f(grp['rate'].mean())} "
            f"[{_f(grp['rate_low'].min())}, {_f(grp['rate_high'].max())}] "
            f"| {_f(grp['rate_unfiltered'].mean())} | {_f(grp['delta'].mean())} |"
        )
    strat = r[(r["feature_set"] == "full") & r["mr"].isin(["MR1", "MR4"]) & (r["stratum"] != "all")]
    lines += [
        "",
        "## MR1 and MR4 by year validity (full-feature models; decision D11)",
        "",
        "| Algorithm | MR | Stratum | Counted | Violation rate (mean over seeds) |",
        "| --- | --- | --- | ---: | ---: |",
    ]
    for (a, mr, st), grp in strat.groupby(["algorithm", "mr", "stratum"], sort=False):
        lines.append(
            f"| {a} | {mr} | {st} | {grp['n_counted'].mean():.0f} | {_f(grp['rate'].mean())} |"
        )
    return "\n".join(lines) + "\n"


# ---- reproduction check (Gate 2, second machine) -----------------------------------------

COUNT_COLUMNS = ("n_counted", "n_violations", "n_unrealistic")
RATE_COLUMNS = ("rate", "rate_low", "rate_unfiltered", "delta")  # rate_low decides Gate 2
KEYS = ("algorithm", "feature_set", "seed", "mr", "stratum")
RATE_TOLERANCE = 0.01


@dataclass(frozen=True)
class Comparison:
    n_rows: int
    identical_rows: int
    max_rate_diff: float
    worst: list[str]
    same_gate: bool

    @property
    def verdict(self) -> str:
        if self.identical_rows == self.n_rows and self.same_gate:
            return "IDENTICAL"
        if self.max_rate_diff <= RATE_TOLERANCE and self.same_gate:
            return "MATCHES"
        return "DIFFERENT"


def compare(reference: pd.DataFrame, rerun: pd.DataFrame) -> Comparison:
    """Compare a re-run pilot CSV with the committed one (MLflow run IDs are ignored).

    IDENTICAL: every count and rate equal. MATCHES: every rate within 0.01 and the same Gate 2
    verdict; small differences can come from a different maths library (e.g. Apple Accelerate
    vs OpenBLAS) in the linear models and the MLP. DIFFERENT: anything else.
    """
    cols = list(KEYS) + list(COUNT_COLUMNS) + list(RATE_COLUMNS)
    ref = reference[cols].set_index(list(KEYS)).sort_index()
    new = rerun[cols].set_index(list(KEYS)).sort_index()
    if not ref.index.equals(new.index):
        raise ValueError("the two pilot results do not cover the same models, MRs and strata")
    rate_diff = (ref[list(RATE_COLUMNS)] - new[list(RATE_COLUMNS)]).abs().fillna(0.0)
    same_counts = (ref[list(COUNT_COLUMNS)] == new[list(COUNT_COLUMNS)]).all(axis=1)
    same_rows = same_counts & (rate_diff.max(axis=1) < 1e-12)
    per_row = rate_diff.max(axis=1).sort_values(ascending=False)
    worst = [
        f"{'/'.join(str(part) for part in k) if isinstance(k, tuple) else k}: {v:.4f}"
        for k, v in per_row.head(5).items()
        if v > 0
    ]

    def passes(df: pd.DataFrame) -> bool:
        return gate2(PilotResult("", "", df, pd.DataFrame())).passes

    return Comparison(
        n_rows=len(ref),
        identical_rows=int(same_rows.sum()),
        max_rate_diff=float(rate_diff.to_numpy().max()) if len(rate_diff) else 0.0,
        worst=worst,
        same_gate=passes(reference) == passes(rerun),
    )


def render_reproduction(
    reference: pd.DataFrame,
    rerun: pd.DataFrame,
    ref_detection: pd.DataFrame,
    rerun_detection: pd.DataFrame,
    label: str,
) -> str:
    """Per-algorithm comparison of a second-machine pilot run with the reference run."""
    c = compare(reference, rerun)
    keys = list(KEYS)
    joined = reference.merge(rerun, on=keys, suffixes=("_ref", "_new"))
    det = ref_detection.merge(
        rerun_detection, on=["algorithm", "feature_set", "seed"], suffixes=("_ref", "_new")
    )
    lines = [
        f"# Pilot reproduction: {label}",
        "",
        "Generated by `shortcutcheck pilot-reproduction`. Reference: the committed pilot results "
        "(`reports/pilot_rq1_rq12-DR-AG*.csv`). Second run: the CSVs in this folder. Verdict rule "
        "(set before the run, PR #7): IDENTICAL = all equal; MATCHES = every rate within "
        f"{RATE_TOLERANCE:g} and the same Gate 2 verdict; DIFFERENT = anything else.",
        "",
        f"**Verdict: {c.verdict}.** Rows identical: {c.identical_rows} of {c.n_rows}. "
        f"Largest rate difference: {c.max_rate_diff:.4f}. "
        f"Same Gate 2 verdict: {'yes' if c.same_gate else 'no'}.",
        "",
        "| Algorithm | Features | Largest detection-metric difference | Rows with different "
        "violation counts | Largest rate difference (all inputs) | Largest rate difference "
        "(any stratum) |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    metrics = ["f1", "pr_auc", "roc_auc", "fpr_at_95tpr"]
    for (a, fs), g in joined.groupby(["algorithm", "feature_set"], sort=False):
        d = det[(det["algorithm"] == a) & (det["feature_set"] == fs)]
        det_diff = max(float((d[f"{m}_ref"] - d[f"{m}_new"]).abs().max()) for m in metrics)
        allr = g[g["stratum"] == "all"]
        lines.append(
            f"| {a} | {fs} | {det_diff:.2e} "
            f"| {int((g['n_violations_ref'] != g['n_violations_new']).sum())} "
            f"| {float((allr['rate_ref'] - allr['rate_new']).abs().max()):.4f} "
            f"| {float((g['rate_ref'] - g['rate_new']).abs().max()):.4f} |"
        )
    return "\n".join(lines) + "\n"
